W,H=1080,140
FB=ImageFont.truetype('/usr/share/fonts/opentype/noto/NotoSansCJK-Bold.ttc',26,index=2)
FR=ImageFont.truetype('/usr/share/fonts/opentype/noto/NotoSansCJK-Regular.ttc',23,index=2)
FL=ImageFont.truetype('/usr/share/fonts/opentype/noto/NotoSansCJK-Bold.ttc',17,index=2)
ACC=(255,122,61); INK=(228,232,236); MUT=(150,159,169); BG=(14,17,21)
for i,(t,ti,plot,cam) in enumerate(CH):
    im=Image.new('RGB',(W,H),BG); d=ImageDraw.Draw(im)
    d.text((28,12),ti,font=FB,fill=ACC)
    for k,(lab,txt) in enumerate((("剧情",plot),("镜头",cam))):
        y=58+k*38
        d.rounded_rectangle([28,y+3,74,y+29],radius=6,fill=(44,50,58)); d.text((34,y+4),lab,font=FL,fill=MUT)
        w=d.textlength(txt,font=FR); assert w<W-28-88, (i,txt,w)
        d.text((88,y),txt,font=FR,fill=INK)
    im.save(f'cap/c{i:02d}.png')
